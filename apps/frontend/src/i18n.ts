export function getLocale(value: string | null | undefined): Locale {
  return locales.includes(value as Locale) ? (value as Locale) : 'es';
}

export function localizedUrl(path: string, locale: Locale): string {
  const hashIndex = path.indexOf('#');
  const base = hashIndex === -1 ? path : path.slice(0, hashIndex);
  const hash = hashIndex === -1 ? '' : path.slice(hashIndex);
  const queryIndex = base.indexOf('?');
  const pathname = queryIndex === -1 ? base : base.slice(0, queryIndex);
  const params = new URLSearchParams(queryIndex === -1 ? '' : base.slice(queryIndex + 1));
  if (locale === 'es') params.delete('lang');
  else params.set('lang', locale);
  const query = params.toString();
  return `${pathname}${query ? `?${query}` : ''}${hash}`;
}

